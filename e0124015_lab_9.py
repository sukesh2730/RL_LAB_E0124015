import gymnasium as gym
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
from collections import defaultdict

env = gym.make('Blackjack-v1')

def sample_policy(state):
    player_score, dealer_card, usable_ace = state
    return 0 if player_score >= 20 else 1

def generate_episode_prediction(env, policy):
    episode = []
    state, info = env.reset()
    done = False
    while not done:
        action = policy(state)
        next_state, reward, done, truncated, info = env.step(action)
        episode.append((state, action, reward))
        state = next_state
    return episode

def first_visit_mc_prediction(env, policy, num_episodes=500000):
    returns_sum = defaultdict(float)
    returns_count = defaultdict(float)
    V = defaultdict(float)

    for i in range(num_episodes):
        episode = generate_episode_prediction(env, policy)
        states_in_episode = [x[0] for x in episode]
        G = 0
        for t in reversed(range(len(episode))):
            state, action, reward = episode[t]
            G += reward
            if state not in states_in_episode[:t]:
                returns_sum[state] += G
                returns_count[state] += 1
                V[state] = returns_sum[state] / returns_count[state]
    return V

def make_epsilon_greedy_policy(Q, epsilon, nA):
    def policy_fn(observation):
        A = np.ones(nA, dtype=float) * epsilon / nA
        best_action = np.argmax(Q[observation])
        A[best_action] += (1.0 - epsilon)
        return A
    return policy_fn

def generate_episode_control(env, policy_fn):
    episode = []
    state, info = env.reset()
    done = False
    while not done:
        probs = policy_fn(state)
        action = np.random.choice(np.arange(len(probs)), p=probs)
        next_state, reward, done, truncated, info = env.step(action)
        episode.append((state, action, reward))
        state = next_state
    return episode

def mc_on_policy_control(env, num_episodes=500000, epsilon=0.1):
    nA = env.action_space.n
    Q = defaultdict(lambda: np.zeros(nA))
    returns_sum = defaultdict(float)
    returns_count = defaultdict(float)

    for i in range(num_episodes):
        policy_fn = make_epsilon_greedy_policy(Q, epsilon, nA)
        episode = generate_episode_control(env, policy_fn)
        state_action_pairs = [(x[0], x[1]) for x in episode]
        G = 0
        for t in reversed(range(len(episode))):
            state, action, reward = episode[t]
            G += reward
            if (state, action) not in state_action_pairs[:t]:
                returns_sum[(state, action)] += G
                returns_count[(state, action)] += 1
                Q[state][action] = returns_sum[(state, action)] / returns_count[(state, action)]
    return Q

def plot_value_function(V, title="Value Function"):
    """Plots the value function as a heatmap for Usable vs No Usable Ace."""
    min_x, max_x = 11, 21
    min_y, max_y = 1, 10

    x_range = np.arange(min_x, max_x + 1)
    y_range = np.arange(min_y, max_y + 1)

    grid_no_ace = np.zeros((len(y_range), len(x_range)))
    grid_ace = np.zeros((len(y_range), len(x_range)))

    for s in V.keys():
        player_score, dealer_card, usable_ace = s
        if min_x <= player_score <= max_x and min_y <= dealer_card <= max_y:
            x_idx = player_score - min_x
            y_idx = dealer_card - min_y
            if usable_ace:
                grid_ace[y_idx, x_idx] = V[s]
            else:
                grid_no_ace[y_idx, x_idx] = V[s]

    fig, axes = plt.subplots(1, 2, figsize=(16, 6))

    sns.heatmap(grid_ace, xticklabels=x_range, yticklabels=y_range, cmap="RdBu", annot=True, fmt=".2f", ax=axes[0], cbar_kws={'label': 'Value Score'})
    axes[0].set_title(f"{title} (Usable Ace)")
    axes[0].set_xlabel("Player Score")
    axes[0].set_ylabel("Dealer Showing Card")
    axes[0].invert_yaxis()

    sns.heatmap(grid_no_ace, xticklabels=x_range, yticklabels=y_range, cmap="RdBu", annot=True, fmt=".2f", ax=axes[1], cbar_kws={'label': 'Value Score'})
    axes[1].set_title(f"{title} (No Usable Ace)")
    axes[1].set_xlabel("Player Score")
    axes[1].set_ylabel("Dealer Showing Card")
    axes[1].invert_yaxis()

    plt.tight_layout()
    plt.show()

def plot_policy(Q, title="Optimal Policy Strategy Map"):
    """Plots the optimal actions (Hit=1 vs Stick=0) as a discrete matrix layout."""
    min_x, max_x = 11, 21
    min_y, max_y = 1, 10

    x_range = np.arange(min_x, max_x + 1)
    y_range = np.arange(min_y, max_y + 1)

    grid_no_ace = np.zeros((len(y_range), len(x_range)))
    grid_ace = np.zeros((len(y_range), len(x_range)))

    for s in Q.keys():
        player_score, dealer_card, usable_ace = s
        if min_x <= player_score <= max_x and min_y <= dealer_card <= max_y:
            x_idx = player_score - min_x
            y_idx = dealer_card - min_y
            best_action = np.argmax(Q[s])
            if usable_ace:
                grid_ace[y_idx, x_idx] = best_action
            else:
                grid_no_ace[y_idx, x_idx] = best_action

    fig, axes = plt.subplots(1, 2, figsize=(16, 6))

    cmap = sns.color_palette(["#ff9999", "#99ff99"])

    sns.heatmap(grid_ace, xticklabels=x_range, yticklabels=y_range, cmap=cmap, linewidths=0.5, linecolor='gray', ax=axes[0], cbar=False)
    axes[0].set_title(f"{title} (Usable Ace)")
    axes[0].set_xlabel("Player Score")
    axes[0].set_ylabel("Dealer Showing Card")
    axes[0].invert_yaxis()
    for y in range(grid_ace.shape[0]):
        for x in range(grid_ace.shape[1]):
            axes[0].text(x + 0.5, y + 0.5, 'HIT' if grid_ace[y, x] == 1 else 'STICK', horizontalalignment='center', verticalalignment='center', weight='bold')

    sns.heatmap(grid_no_ace, xticklabels=x_range, yticklabels=y_range, cmap=cmap, linewidths=0.5, linecolor='gray', ax=axes[1], cbar=False)
    axes[1].set_title(f"{title} (No Usable Ace)")
    axes[1].set_xlabel("Player Score")
    axes[1].set_ylabel("Dealer Showing Card")
    axes[1].invert_yaxis()
    for y in range(grid_no_ace.shape[0]):
        for x in range(grid_no_ace.shape[1]):
            axes[1].text(x + 0.5, y + 0.5, 'HIT' if grid_no_ace[y, x] == 1 else 'STICK', horizontalalignment='center', verticalalignment='center', weight='bold')

    plt.tight_layout()
